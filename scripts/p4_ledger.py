#!/usr/bin/env python3
"""Write docs/PHASE4_JOB_LEDGER.md from the local queue ledgers (read-only on logs/).

    python3 scripts/p4_ledger.py [repo_root]

Reads logs/phase4_queue/{full,extra,budget,owl}/status.tsv (written by
scripts/p4_queue.sh; gitignored) and writes one table per round: queue, start,
end, hours, exit code, output directory and the exact command. A START with no
END (stopped by hand) is listed separately. Standard library only.
"""
import os
import re
import sys
from datetime import datetime

REPO = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROUNDS = [("full", "Round 1 (17-18 Nov): main plan"),
          ("extra", "Round 1 (17-18 Nov): extra checks"),
          ("budget", "Round 2 (18 Nov): 4/255 budget, 300 images"),
          ("owl", "Round 2 (18 Nov): fourth model, OWL-ViT")]
FMT = "%Y-%m-%d %H:%M:%S"


def short(cmd):
    cmd = cmd.replace("python phase4/", "").replace("python3 phase4/", "")
    return re.sub(r"\s+", " ", cmd).strip()


def outdir(cmd):
    m = re.search(r"--output-dir (\S+)", cmd)
    if m:
        return m.group(1).replace("results/phase4/", "")
    exp = re.search(r"--experiment (\S+)", cmd)
    model = re.search(r"p4_(\w+)\.py", cmd).group(1)
    if "p4_smolvlm" in cmd:
        return "presence_qa_smolvlm"
    return f"{exp.group(1)}_{model}" if exp else model


def main():
    lines = ["# Phase-4 job ledger",
             "",
             "Every GPU job of the Phase-4 runs. One NVIDIA RTX 5000 Ada (32 GB) ran all of them; "
             "up to 8 jobs (round 1) and 9 jobs (round 2) shared the GPU, so the durations are not single-job speeds.",
             "",
             "- Generated by `scripts/p4_ledger.py` from the queue ledgers `logs/phase4_queue/<mode>/status.tsv`. Those, and the "
             "per-queue console logs, stay local (gitignored).",
             "- Each job's own transcript is committed as `run*.log` next to its summaries, in the "
             "directory under `results/phase4/` given in the *Output* column.",
             "- Exit 0 means the job finished and wrote its summary.",
             ""]
    total = failed = 0
    for mode, title in ROUNDS:
        path = os.path.join(REPO, "logs", "phase4_queue", mode, "status.tsv")
        open_jobs, done, stopped = {}, [], []
        for raw in open(path):
            f = raw.rstrip("\n").split("\t")
            ts, job, ev = f[0], f[1], f[2]
            cmd = f[5] if len(f) > 5 else ""
            if ev == "START":
                if job in open_jobs:
                    stopped.append((job, open_jobs[job][0], open_jobs[job][1]))
                open_jobs[job] = (ts, cmd)
            elif ev == "END":
                st, scmd = open_jobs.pop(job)
                assert scmd == cmd, (job, scmd, cmd)
                done.append((st, ts, job, int(f[3]), int(f[4]), cmd))
        for job, (st, cmd) in open_jobs.items():
            stopped.append((job, st, cmd))
        lines += [f"## {title}", "",
                  "| Queue | Start | End | Hours | Exit | Output (`results/phase4/`) | Command |",
                  "|---|---|---|---|---|---|---|"]
        for st, en, job, code, sec, cmd in sorted(done):
            total += 1
            failed += code != 0
            lines.append(f"| {job} | {st[5:16]} | {en[5:16]} | {sec / 3600:.1f} | {code} | "
                         f"`{outdir(cmd)}` | `{short(cmd)}` |")
        t0 = min(d[0] for d in done)
        t1 = max(d[1] for d in done)
        wall = (datetime.strptime(t1, FMT) - datetime.strptime(t0, FMT)).total_seconds() / 3600
        lines += ["", f"{len(done)} jobs, {sum(d[3] != 0 for d in done)} failed, "
                      f"{t0[5:16]} to {t1[5:16]} ({wall:.1f} h wall clock).", ""]
        if stopped:
            lines.append("Started but stopped by hand (no result, nothing cited):")
            lines.append("")
            for job, st, cmd in sorted(stopped, key=lambda s: s[1]):
                why = ("2/255 budget dropped for time" if "eps2" in job or "--eps 0.008" in cmd
                       else "restarted at the next START of the same queue")
                lines.append(f"- `{job}`, started {st[5:16]}: {why}.")
            lines.append("")
    lines += ["## CPU jobs (no GPU)", "",
              "- `scripts/p4_boot_survey.py` on the OWL-ViT survey checkpoint, B=1,000, 8 workers, "
              "18 Nov (176 s): wrote `results/phase4/oblivious_survey_owl/"
              "summary_bootstrap_oblivious_survey_owl_seed1.json`.",
              "- `scripts/p4_subset_score.py`: first-300 re-scores of the 1,000-image checkpoints, "
              "in `results/phase4/budget_curve_eps7of255_first300/` and "
              "`results/phase4/adaptive_bpda_owl_n300/`.",
              "",
              f"**Total: {total} GPU jobs, {failed} failed.**", ""]
    out = os.path.join(REPO, "docs", "PHASE4_JOB_LEDGER.md")
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print(out, total, failed)


if __name__ == "__main__":
    main()
